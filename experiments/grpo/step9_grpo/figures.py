"""nzd's step 6 comparison figures, for the start model against GRPO. (CPU, bricknet env with bricknet-render)

Runs nzd-supertry/step6_render_score/figures/make_figures.py unchanged (read only), loaded as a module with
the model columns switched to the start model (masked) and GRPO: four panels per case, sharing one camera,

  Input | Ground truth | Start: masked order | GRPO (step 300)

in the natural and highlight styles (highlight: reference M blue, placed right green, right part in the wrong
place orange, not a part of M red). Each model shows its best of 8 samples, as in nzd's figures. Renders on the
CPU (--device CPU), so the shared GPU is not used.

The cases are picked by hand from select_cases.py's candidates (step9_grpo/figures/*.json);
they illustrate examples. Quantitative report results are generated by reproduction/scripts/reproduce.py.

Usage (from ~/RL):
  python step9_grpo/figures.py --cases step9_grpo/figures/grpo_only.json --out runs/r1/figures/grpo_only
  python step9_grpo/figures.py --cases step9_grpo/figures/start_only.json --out runs/r1/figures/start_only
  (extra arguments go to make_figures.py: --only <case>, --styles natural, --no-render, --samples, ...)
"""

import argparse
import importlib.util
import os
import subprocess
import sys
from pathlib import Path

SRC = Path(os.environ.get("SRC", "/home/nzd0420/brickICL"))  # nzd's repo root, from env.sh
FIG = SRC / "nzd-supertry/step6_render_score/figures"
RFT = Path(__file__).resolve().parent.parent
MODELS = ("masked", "grpo")
LABELS = {"masked": "Start: masked order", "grpo": "GRPO (step 300)"}


class CpuRender:
    """Stands in for make_figures' subprocess module: the renderer defaults to the GPU, render on the CPU."""

    @staticmethod
    def run(cmd, **kw):
        return subprocess.run([*cmd, "--device", "CPU"], **kw)


def load_make_figures():
    # rft's own `common` package would shadow nzd's step6 `common` (a folder without __init__.py)
    sys.path[:] = [p for p in sys.path if Path(p or ".").resolve() != RFT]
    sys.modules.pop("common", None)
    spec = importlib.util.spec_from_file_location("nzd_make_figures", FIG / "make_figures.py")
    mf = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mf)
    import common.assemble as assemble

    mf.MODELS, mf.VARIANTS = MODELS, ("context", "reference", *MODELS)
    mf.LABELS |= LABELS
    mf.load_eval = lambda d: assemble.load_eval(d, models=MODELS)
    mf.subprocess = CpuRender
    return mf


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--round", type=Path, default=Path("runs/r1"))
    ap.add_argument("--cases", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args, rest = ap.parse_known_args()
    links = (args.round / "viewer/eval").resolve()  # test.jsonl + <model>.jsonl links, made by step9_grpo/viewer.py
    assert (links / "grpo.jsonl").exists(), "run step9_grpo/viewer.py first (it links the result files)"
    mf = load_make_figures()
    sys.argv = [str(FIG / "make_figures.py"), str(links), "--cases", str(args.cases.resolve()),
                "--out", str(args.out.resolve()), *rest]
    mf.main()


if __name__ == "__main__":
    main()
